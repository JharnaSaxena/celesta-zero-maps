// Serverless-friendly PostgreSQL pool for Vercel + Neon (or another Postgres provider).
import pg from 'pg';
import crypto from 'node:crypto';

const { Pool } = pg;
const connectionString = process.env.DATABASE_URL || process.env.POSTGRES_URL;
if (!connectionString) {
  throw new Error('Set DATABASE_URL (or POSTGRES_URL) to a PostgreSQL connection string.');
}

export const db = new Pool({
  connectionString,
  max: Number(process.env.PG_POOL_MAX) || 2,
  idleTimeoutMillis: 10_000,
  connectionTimeoutMillis: 10_000,
  allowExitOnIdle: true,
});

const schema = `
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  pw_salt BYTEA NOT NULL,
  pw_hash BYTEA NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS workspaces (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  rev INTEGER NOT NULL DEFAULT 1,
  updated_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS briefings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_briefings_user ON briefings(user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  event TEXT NOT NULL,
  ip TEXT,
  created_at BIGINT NOT NULL
);
`;

export const now = () => Math.floor(Date.now() / 1000);
export const sha256 = (value) => crypto.createHash('sha256').update(value).digest('hex');

// The archive's routes use prepared statements with '?' placeholders. Translate
// those to PostgreSQL parameters while preserving parameterized SQL throughout.
const postgresSql = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

export const statements = {
  async get(sql, ...values) {
    const result = await db.query(postgresSql(sql), values);
    return result.rows[0];
  },
  async all(sql, ...values) {
    const result = await db.query(postgresSql(sql), values);
    return result.rows;
  },
  async run(sql, ...values) {
    const result = await db.query(postgresSql(sql), values);
    return { lastInsertRowid: result.rows[0]?.id, changes: result.rowCount };
  },
};

export async function audit(userId, event, ip) {
  await db.query(
    'INSERT INTO audit_log (user_id, event, ip, created_at) VALUES ($1,$2,$3,$4)',
    [userId ?? null, event, ip ?? null, now()],
  );
}

export async function purgeExpired() {
  await db.query('DELETE FROM sessions WHERE expires_at < $1', [now()]);
}

// Create tables before this module is used by Express. This is idempotent and
// makes first deploys work without a separate migration command.
await db.query(schema);
